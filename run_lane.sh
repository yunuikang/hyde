#!/bin/bash
# One lane per Backend.AI session (all sessions share /home/work/yunuikang, results merge automatically).
#   bash run_lane.sh A      [threads]   # session 1: Tier A (8 datasets)  E1 -> E2 -> E3 -> E4 -> E5   (GPU)
#   bash run_lane.sh B      [threads]   # session 2: Tier B (3 large)     E1 -> E2 -> E3 -> E4 -> E5   (GPU)
#   bash run_lane.sh ML     [threads]   # session 3: E0 ML baselines, all 11 datasets              (CPU)
#   bash run_lane.sh COST   [threads]   # LAST, ALONE on an idle session: E6 cost benchmark
# Launch:  nohup bash run_lane.sh A 6 >> logs/lane_A.log 2>&1 &
# Safe to re-run any time (finished results are skipped). Never run the same lane twice at once.
# Progress: python status.py          (do NOT edit this file while it runs)
set -u
cd "$(dirname "$0")"
mkdir -p logs
LANE=${1:?lane A|B|ML|COST}
T=${2:-6}
PY=${PY:-/home/work/yunuikang/miniconda3/envs/final-env/bin/python3}
A="mirai nsl-kdd unsw-nb15 ton-iot cicids2017 xiiotid wustl-iiot-2021 edge-iiot"
B="cicids2018 lspr23 nf-ton-iot-v3"
log() { echo "[lane $LANE] $* $(date)"; }
log "start (threads $T)"
case "$LANE" in
  A|B)
    DS=${!LANE}
    $PY jobs.py cache --datasets $DS >> "logs/${LANE}_cache.log" 2>&1
    for st in E1 E2 E3 E4 E5; do
        $PY jobs.py "$st" --datasets $DS --threads "$T" >> "logs/${LANE}_${st}.log" 2>&1
        log "$st done"
    done ;;
  ML)
    $PY jobs.py E0 --datasets $A $B --threads "$T" >> logs/ML_E0.log 2>&1
    log "E0 done" ;;
  COST)
    $PY jobs.py E6 --datasets $A $B --threads "$T" >> logs/COST_E6.log 2>&1
    log "E6 done" ;;
  *) echo "unknown lane $LANE"; exit 1 ;;
esac
log "finished"
